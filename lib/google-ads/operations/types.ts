export interface PlanFailure {
  failure: MutateResult;
  stepIndex: number;
  /** Steps that were already applied before the failure. */
  appliedSteps: number;
}

async function runStep(step: MutationStep, context: GoogleAdsContext, validateOnly: boolean) {
  if (step.kind === 'service') {
    const result = await mutateGoogleAdsResources(step.service, step.operations, context, { validateOnly });
    return { result, stepResult: { results: result.results } as StepResult };
  }
  const result = await mutateGoogleAdsCombined(step.operations, context, { validateOnly });
  return { result, stepResult: { responses: result.responses } as StepResult };
}

/**
 * Ask Google Ads to validate the plan without applying it. Only steps that do
 * not depend on IDs created by earlier steps can be validated in advance.
 */
export async function preflightPlan(steps: PlannedStep[], context: GoogleAdsContext): Promise<PlanFailure | undefined> {
  for (let index = 0; index < steps.length; index += 1) {
    const step = steps[index];
    if (typeof step === 'function') break;
    const { result } = await runStep(step, context, true);
    if (!result.success) return { failure: result, stepIndex: index, appliedSteps: 0 };
  }
  return undefined;
}

/** Apply the plan step by step. Each step is atomic on the Google Ads side. */
export async function applyPlan(
  steps: PlannedStep[],
  context: GoogleAdsContext
): Promise<{ ok: true; results: StepResult[] } | ({ ok: false; results: StepResult[] } & PlanFailure)> {
  const results: StepResult[] = [];
  for (let index = 0; index < steps.length; index += 1) {
    const planned = steps[index];
    const step = typeof planned === 'function' ? planned(results) : planned;
    if (!step) {
      results.push({});
      continue;
    }
    const { result, stepResult } = await runStep(step, context, false);
    if (!result.success) {
      return { ok: false, results, failure: result, stepIndex: index, appliedSteps: index };
    }
    results.push(stepResult);
  }
  return { ok: true, results };
}

/** Resource names returned by a service mutate or a combined mutate. */
export function resultResourceNames(result: StepResult | undefined): string[] {
  if (!result) return [];
  const names: string[] = [];
  for (const item of result.results || []) {
    if (typeof item.resourceName === 'string') names.push(item.resourceName);
  }
  for (const response of result.responses || []) {
    for (const value of Object.values(response)) {
      const name = (value as { resourceName?: string } | undefined)?.resourceName;
      if (typeof name === 'string') names.push(name);
    }
  }
  return names;
}
