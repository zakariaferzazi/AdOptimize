/**
 * Shared contracts for validated Google Ads write operations.
 *
 * The model never sends raw mutate payloads. It calls a business-level
 * operation with a strict schema; the operation reads live state, validates
 * the request semantically, describes the change, and later builds the exact
 * mutations, detects drift and verifies the result. The proposal engine, the
 * executor and the MCP surface all use these same descriptors.
 */

export interface JsonSchemaProperty {
  type: 'string' | 'number' | 'boolean' | 'array' | 'object';
  description?: string;
  enum?: string[];
  items?: JsonSchemaProperty;
  properties?: Record<string, JsonSchemaProperty>;
  required?: string[];
  additionalProperties?: false;
  minimum?: number;
  maximum?: number;
  minItems?: number;
  maxItems?: number;
  maxLength?: number;
}

export interface OperationSchema {
  type: 'object';
  properties: Record<string, JsonSchemaProperty>;
  required?: string[];
  additionalProperties?: false;
}

export interface ProposalTarget {
  kind: 'account' | 'campaign' | 'ad_group' | 'keyword' | 'new_campaign';
  campaignId?: string;
  campaignName?: string;
  adGroupId?: string;
  adGroupName?: string;
  criterionId?: string;
  label: string;
}

export interface PreparedChange {
  /** Normalised payload that is stored, hashed and later executed. */
  args: Record<string, unknown>;
  /** One sentence describing the change. */
  summary: string;
  /** Human-readable before → after lines for the approval card. */
  changes: string[];
  /** Live state captured at proposal time, used for drift detection. */
  before: Record<string, unknown>;
  target: ProposalTarget;
  warnings: string[];
}

export type MutationStep =
  | { kind: 'service'; service: MutateService; operations: MutateOperation[] }
  | { kind: 'combined'; operations: Array<Record<string, unknown>> };

export interface StepResult {
  results?: Array<Record<string, unknown>>;
  responses?: Array<Record<string, unknown>>;
}

/** A step that depends on resource names created by earlier steps. */
export type DeferredStep = (prior: StepResult[]) => MutationStep | null;

export type PlannedStep = MutationStep | DeferredStep;

export type ActionType = ProposedAccountChange['actionType'];

export interface OperationDescriptor {
  name: string;
  /** Short label for cards and logs. */
  title: string;
  /** Model-facing description: what it does, when to use it, what it cannot do. */
  description: string;
  schema: OperationSchema;
  /** Payload keys generated by `prepare` that the model cannot supply but execution accepts. */
  internalArgs?: string[];
  actionType(args: Record<string, unknown>): ActionType;
  /** Destructive changes (stopping delivery, removing) need explicit acknowledgement. */
  destructive(args: Record<string, unknown>): boolean;
  /** Identity of the thing being changed; a newer proposal with the same key in the same task supersedes the older one. */
  targetKey(args: Record<string, unknown>): string;
  prepare(args: Record<string, unknown>, context: GoogleAdsContext): Promise<PreparedChange>;
  /** Fresh read of the state this operation changes. `realIds` is set after creates. */
  readState(
    args: Record<string, unknown>,
    context: GoogleAdsContext,
    realIds?: Record<string, string>
  ): Promise<Record<string, unknown>>;
  /** Keys of `before` that must still match the live state at execution time. */
  driftKeys: string[];
  plan(
    args: Record<string, unknown>,
    context: GoogleAdsContext,
    state: Record<string, unknown>
  ): PlannedStep[];
  realIds?(args: Record<string, unknown>, results: StepResult[], context: GoogleAdsContext): Record<string, string>;
  /** Returns mismatches between the requested change and the read-back; empty when verified. */
  verify(args: Record<string, unknown>, after: Record<string, unknown>, realIds: Record<string, string>): string[];
}

// ---------------------------------------------------------------------------
// Schema normalisation and validation
// ---------------------------------------------------------------------------

function coerce(value: unknown, schema: JsonSchemaProperty): unknown {
  if (value === null || value === undefined) return undefined;
  switch (schema.type) {
    case 'number':
      if (typeof value === 'string' && value.trim() !== '' && Number.isFinite(Number(value.replace(/,/g, '')))) {
        return Number(value.replace(/,/g, ''));
      }
      return value;
    case 'boolean':
      if (value === 'true') return true;
      if (value === 'false') return false;
      return value;
    case 'string':
      if (typeof value === 'number') return String(value);
      return typeof value === 'string' ? value.trim() : value;
    case 'array':
      return Array.isArray(value) && schema.items ? value.map((item) => coerce(item, schema.items!)) : value;
    case 'object':
      if (value && typeof value === 'object' && !Array.isArray(value) && schema.properties) {
        const result: Record<string, unknown> = {};
        for (const [key, item] of Object.entries(value as Record<string, unknown>)) {
          const property = schema.properties[key];
          const coerced = property ? coerce(item, property) : item;
          if (coerced !== undefined && coerced !== '') result[key] = coerced;
        }
        return result;
      }
      return value;
    default:
      return value;
  }
}

/**
 * Lenient normalisation before strict validation: numeric strings become
 * numbers, "true"/"false" become booleans, empty optional values are dropped.
 */
export function normalizeArgs(schema: OperationSchema, args: Record<string, unknown>): Record<string, unknown> {
  return coerce(args || {}, { type: 'object', properties: schema.properties }) as Record<string, unknown>;
}

function validateValue(path: string, value: unknown, schema: JsonSchemaProperty, errors: string[]): void {
  switch (schema.type) {
    case 'number':
      if (typeof value !== 'number' || !Number.isFinite(value)) {
        errors.push(`"${path}" must be a number.`);
        return;
      }
      if (schema.minimum !== undefined && value < schema.minimum) errors.push(`"${path}" must be at least ${schema.minimum}.`);
      if (schema.maximum !== undefined && value > schema.maximum) errors.push(`"${path}" must be at most ${schema.maximum}.`);
      return;
    case 'boolean':
      if (typeof value !== 'boolean') errors.push(`"${path}" must be true or false.`);
      return;
    case 'string':
      if (typeof value !== 'string') {
        errors.push(`"${path}" must be a string.`);
        return;
      }
      if (schema.enum && !schema.enum.includes(value)) errors.push(`"${path}" must be one of: ${schema.enum.join(', ')}.`);
      if (schema.maxLength !== undefined && value.length > schema.maxLength) {
        errors.push(`"${path}" must be at most ${schema.maxLength} characters (got ${value.length}).`);
      }
      return;
    case 'array':
      if (!Array.isArray(value)) {
        errors.push(`"${path}" must be an array.`);
        return;
      }
      if (schema.minItems !== undefined && value.length < schema.minItems) errors.push(`"${path}" needs at least ${schema.minItems} items.`);
      if (schema.maxItems !== undefined && value.length > schema.maxItems) errors.push(`"${path}" allows at most ${schema.maxItems} items.`);
      if (schema.items) value.forEach((item, index) => validateValue(`${path}[${index}]`, item, schema.items!, errors));
      return;
    case 'object': {
      if (!value || typeof value !== 'object' || Array.isArray(value)) {
        errors.push(`"${path}" must be an object.`);
        return;
      }
      validateObject(path, value as Record<string, unknown>, schema.properties || {}, schema.required || [], schema.additionalProperties, errors);
      return;
    }
  }
}

function validateObject(
  prefix: string,
  value: Record<string, unknown>,
  properties: Record<string, JsonSchemaProperty>,
  required: string[],
  additionalProperties: false | undefined,
  errors: string[]
): void {
  const name = (key: string) => (prefix ? `${prefix}.${key}` : key);
  for (const key of required) {
    if (value[key] === undefined || value[key] === null || value[key] === '') errors.push(`"${name(key)}" is required.`);
  }
  for (const [key, item] of Object.entries(value)) {
    if (item === undefined) continue;
    const definition = properties[key];
    if (!definition) {
      if (additionalProperties === false) errors.push(`"${name(key)}" is not a supported parameter.`);
      continue;
    }
    validateValue(name(key), item, definition, errors);
  }
}

export function validateOperationArgs(
  operation: Pick<OperationDescriptor, 'schema' | 'internalArgs'>,
  args: Record<string, unknown>,
  options: { allowInternal?: boolean } = {}
): { valid: boolean; errors: string[] } {
  const errors: string[] = [];
  const { properties, required = [], additionalProperties } = operation.schema;
  let checked = args;
  if (options.allowInternal && operation.internalArgs?.length) {
    checked = Object.fromEntries(Object.entries(args).filter(([key]) => !operation.internalArgs!.includes(key)));
  }
  validateObject('', checked, properties, required, additionalProperties, errors);
  return { valid: errors.length === 0, errors };
}

