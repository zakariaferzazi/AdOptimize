export function customerPath(context: GoogleAdsContext): string {
  return `customers/${context.customerId.replace(/\D/g, '')}`;
}

export function formatMoney(value: number | undefined | null, currency: string): string {
  if (value === undefined || value === null || !Number.isFinite(value)) return 'not set';
  try {
    return new Intl.NumberFormat('en-US', { style: 'currency', currency }).format(value);
  } catch {
    return `${value.toFixed(2)} ${currency}`;
  }
}

export function humanize(value: unknown): string {
  return String(value ?? '').replace(/_/g, ' ').toLowerCase();
}

/** Reject money values stated in a currency other than the account's. */
export function assertAccountCurrency(args: Record<string, unknown>, context: GoogleAdsContext): void {
  const requested = typeof args.currency === 'string' ? args.currency.trim().toUpperCase() : '';
  if (!requested) return;
  const account = (context.currency || '').toUpperCase();
  if (account && requested !== account) {
    throw invalidArgument(
      `This Google Ads account is billed in ${account}. Budgets and bids are always set in the account currency, so ${requested} amounts cannot be applied directly. Ask the user for the ${account} amount (or offer an approximate conversion for them to confirm).`
    );
  }
}

export function normalizeKeywordText(text: string): string {
  return text.replace(/^[[+"]+|[\]"]+$/g, '').replace(/\s+/g, ' ').trim().toLowerCase();
}

export function validateKeywordList(keywords: Array<{ text: string; matchType: string }>): Array<{ text: string; matchType: string }> {
  const seen = new Set<string>();
  const cleaned: Array<{ text: string; matchType: string }> = [];
  for (const keyword of keywords) {
    const text = normalizeKeywordText(keyword.text);
    if (!text) continue;
    if (text.split(' ').length > 10) throw invalidArgument(`Keyword "${text}" has more than 10 words.`);
    if (/[!@%^*=;<>]/.test(text)) throw invalidArgument(`Keyword "${text}" contains characters Google Ads does not allow.`);
    const key = `${text}|${keyword.matchType}`;
    if (seen.has(key)) continue;
    seen.add(key);
    cleaned.push({ text, matchType: keyword.matchType });
  }
  if (!cleaned.length) throw invalidArgument('No valid keywords were provided.');
  return cleaned;
}

